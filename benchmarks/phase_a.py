"""Measure DISECTA CLI latency and validate Phase A on hand-checked fixtures."""
import argparse
import hashlib
import json
import os
import platform
import statistics
import subprocess
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXPECTED = {"branch.exe": 0x140001000, "branch.elf": 0x401000}


def invoke(binary, arguments):
    start = time.perf_counter_ns()
    result = subprocess.run([binary, *arguments], check=True, capture_output=True)
    return json.loads(result.stdout), (time.perf_counter_ns() - start) / 1_000_000


def measure(binary, fixture, entry, repeats):
    commands = {
        "inspect": ["inspect", fixture, "--json"],
        "disasm": ["disasm", fixture, "--start", hex(entry), "--count", "256", "--json"],
        "analyze": ["analyze", fixture, "--json"],
        "cfg": ["cfg", fixture, "--function", hex(entry), "--json"],
    }
    metrics = {}
    reports = {}
    for name, arguments in commands.items():
        reports[name], _ = invoke(binary, arguments)
        samples = sorted(invoke(binary, arguments)[1] for _ in range(repeats))
        metrics[name] = {
            "median_ms": round(statistics.median(samples), 3),
            "p95_ms": round(statistics.quantiles(samples, n=20, method="inclusive")[18], 3),
        }

    actual_functions = {int(item["address"], 0) for item in reports["analyze"]["functions"]}
    expected_functions = {entry, entry + 0x24}
    actual_edges = {
        (int(edge["from"], 0) - entry, edge["kind"],
         int(edge["target"], 0) - entry if edge["target"] else None)
        for edge in reports["cfg"]["edges"]
    }
    expected_edges = {
        (0, "call", 0x24), (0, "fallthrough", 0xF), (0xF, "branch_taken", 0x1B),
        (0xF, "fallthrough", 0x13), (0x13, "fallthrough", 0x1B), (0x1B, "return", None),
    }
    if actual_functions != expected_functions or actual_edges != expected_edges:
        raise SystemExit(f"{fixture.name}: observed functions or edges differ from fixture ground truth")
    return {
        "fixture": fixture.name,
        "sha256": hashlib.sha256(fixture.read_bytes()).hexdigest(),
        "function_entries_matched": len(actual_functions & expected_functions),
        "function_entries_expected": len(expected_functions),
        "cfg_edges_matched": len(actual_edges & expected_edges),
        "cfg_edges_expected": len(expected_edges),
        "limited": reports["analyze"]["limited"],
        "cli_wall_clock": metrics,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("disecta", type=Path)
    parser.add_argument("--runs", type=int, default=30)
    parser.add_argument("--build", required=True, help="Toolchain, target and build profile of disecta")
    args = parser.parse_args()
    if args.runs < 2:
        parser.error("--runs must be at least 2")
    binary = args.disecta.resolve(strict=True)
    print(json.dumps({
        "build": args.build,
        "binary_sha256": hashlib.sha256(binary.read_bytes()).hexdigest(),
        "system": {"os": platform.platform(), "machine": platform.machine(), "logical_cpus": os.cpu_count(),
                   "cpu": platform.processor()},
        "method": "End-to-end CLI time with process startup, file I/O, analysis and JSON output, "
                  "one warm-up per operation; fixtures are generated byte-for-byte by tests/fixtures/generate.py.",
        "runs_per_operation": args.runs,
        "fixtures": [measure(binary, ROOT / "tests" / "fixtures" / name, entry, args.runs)
                     for name, entry in EXPECTED.items()],
    }, indent=2))


if __name__ == "__main__":
    main()
